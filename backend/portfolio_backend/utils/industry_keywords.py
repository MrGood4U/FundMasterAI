def classify_stock(stock_name: str) -> str:
    """根据股票名称返回行业分类。

    按 INDUSTRY_RULES 优先级匹配，命中第一个即返回。
    例如 "恒瑞医药" → 医药（"药"在"医"之前命中），"比亚迪" → 汽车（"车"匹配）。

    Args:
        stock_name: 股票名称，如 "贵州茅台"、"恒瑞医药"

    Returns:
        行业名称，未匹配则返回 "其他"
    """
    if not stock_name:
        return "其他"
    for industry, keywords in INDUSTRY_RULES:
        for kw in keywords:
            if kw in stock_name:
                return industry
    return "其他"
